const currentLanguage = ref<AppLanguage>('zh-CN')

export function setAppLanguage(language: AppLanguage) {
  currentLanguage.value = language
  document.documentElement.lang = language
}

export function translate(key: TranslationKey, params: Record<string, string | number> = {}) {
  let message: string = (currentLanguage.value === 'en-US' ? enUS : zhCN)[key]
  for (const [name, value] of Object.entries(params)) message = message.replaceAll(`{{${name}}}`, String(value))
  return message
}

export function useI18n() {
  return { t: translate, language: currentLanguage }
}
